#!/usr/bin/env python3
"""Generate pass-through export stubs for a proxy DLL.

Input: a text file with one export per line: "<ExportName> <stdcall arg bytes>".
Output (in outdir):
  stubs.S    - one 'jmp *g_exp_ptrs[i]' stub per export, plus 'return 0' fallbacks
  exports.def- maps each real export name to its stub
  exptab.c   - the name table used to resolve the real DLL at load time

Every export jumps through g_exp_ptrs[i]. At load time the core fills the table
from the real DLL, and the proxy then swaps in its own hook for the one or two
functions it cares about (e.g. wglSwapBuffers). Arguments are never touched,
so the stub works for any calling convention.
"""
import sys, os

src, dllname, outdir = sys.argv[1], sys.argv[2], sys.argv[3]
exps = []
for line in open(src):
    line = line.strip()
    if not line or line.startswith('#'):
        continue
    name, n = line.split()
    exps.append((name, int(n)))

os.makedirs(outdir, exist_ok=True)
sizes = sorted({n for _, n in exps})

with open(os.path.join(outdir, 'stubs.S'), 'w') as f:
    f.write('/* generated by gen_stubs.py - do not edit */\n.text\n')
    for i, _ in enumerate(exps):
        f.write(f'.globl _xs_{i}\n_xs_{i}: jmp *_g_exp_ptrs+{4*i}\n')
    for n in sizes:
        # fallback for an export the real DLL lacks: return 0 and pop args
        f.write(f'.globl _xfb_{n}\n_xfb_{n}: xorl %eax,%eax\n')
        f.write('  ret\n' if n == 0 else f'  ret ${n}\n')

with open(os.path.join(outdir, 'exports.def'), 'w') as f:
    f.write(f'LIBRARY {dllname}\nEXPORTS\n')
    for i, (name, _) in enumerate(exps):
        f.write(f'{name}=xs_{i} @{i+1}\n')

with open(os.path.join(outdir, 'exptab.c'), 'w') as f:
    f.write('/* generated by gen_stubs.py - do not edit */\n')
    for n in sizes:
        f.write(f'extern void xfb_{n}(void);\n')
    f.write(f'const int g_exp_count = {len(exps)};\n')
    f.write('const char *const g_exp_names[] = {\n')
    for name, _ in exps:
        f.write(f'  "{name}",\n')
    f.write('};\n')
    f.write(f'void *g_exp_ptrs[{len(exps)}];\n')
    f.write('void *const g_exp_fallback[] = {\n')
    for _, n in exps:
        f.write(f'  (void *)xfb_{n},\n')
    f.write('};\n')
